def _shape_stock_rows():
    """零件库按形状汇总成表格行（颜色 × 库存），供系统提示词使用。"""
    rows = []
    for s in SHAPES:
        stocks = STOCK[s["id"]]
        values = set(stocks.values())
        if len(values) == 1:
            stock_txt = f"每色 {values.pop()}"
        else:
            stock_txt = "、".join(f"{c}{n}" for c, n in stocks.items() if n > 0)
        rows.append(f"| {s['name']} | {s['w']}×{s['d']} | {s['defaultColor']} | {stock_txt} |")
    return "\n".join(rows)


